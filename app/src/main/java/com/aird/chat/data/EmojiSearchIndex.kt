    fun search(query: String): List<String> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()
        return entries.filter { entry ->
            entry.tags.any { tag -> tag.contains(q) } || entry.emoji == q
        }.map { it.emoji }.distinct()
    }
